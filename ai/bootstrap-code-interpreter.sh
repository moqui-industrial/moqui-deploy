#!/bin/bash
# Prepares a pinned, local Code Interpreter checkout and private deployment secrets.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="$HERE/.code-interpreter"
ENV_FILE="$HERE/.code-interpreter.env"
LIBRECHAT_OVERRIDE="$HERE/.code-interpreter-librechat.generated.yml"
REF="${CODE_INTERPRETER_REF:-v1.0.0}"

command -v docker >/dev/null
command -v git >/dev/null
command -v node >/dev/null
command -v openssl >/dev/null

if [ ! -d "$SOURCE_DIR/.git" ]; then
    git clone --depth 1 --branch "$REF" https://github.com/LibreChat-AI/code-interpreter.git "$SOURCE_DIR"
else
    test "$(git -C "$SOURCE_DIR" describe --tags --exact-match 2>/dev/null || true)" = "$REF" || {
        echo "$SOURCE_DIR is not pinned at $REF; remove it explicitly before changing versions" >&2
        exit 1
    }
fi

if [ ! -f "$ENV_FILE" ]; then
    private_key="$(openssl genpkey -algorithm ED25519 2>/dev/null)"
    private_key_base64="$(printf '%s' "$private_key" | base64 -w 0)"
    public_jwk="$(printf '%s' "$private_key" | node -e '
const crypto = require("crypto");
let pem = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", chunk => pem += chunk);
process.stdin.on("end", () => {
  const key = crypto.createPrivateKey(pem);
  const publicJwk = crypto.createPublicKey(key).export({ format: "jwk" });
  publicJwk.kid = "moqui-codeapi-1";
  publicJwk.alg = "EdDSA";
  publicJwk.use = "sig";
  process.stdout.write(JSON.stringify({ keys: [publicJwk] }));
});
')"
    umask 077
    cat > "$ENV_FILE" <<EOF
LOCAL_MODE=false
CODEAPI_JWT_JWKS_JSON='$public_jwk'
CODEAPI_BRIDGE_TOKEN=$(openssl rand -hex 32)
CODEAPI_INTERNAL_SERVICE_TOKEN=$(openssl rand -hex 32)
CODEAPI_EGRESS_GRANT_SECRET=$(openssl rand -hex 32)
CODEAPI_REDIS_PASSWORD=$(openssl rand -hex 24)
CODEAPI_MINIO_ACCESS_KEY=moqui-codeapi
CODEAPI_MINIO_SECRET_KEY=$(openssl rand -hex 24)
CODEAPI_JWT_PRIVATE_KEY_BASE64=$private_key_base64
CODEAPI_EXECUTION_MANIFEST_PRIVATE_KEY=$(openssl genpkey -algorithm ED25519 -outform DER 2>/dev/null | base64 -w 0)
EOF
    chmod 600 "$ENV_FILE"
fi

manifest_key="$(sed -n 's/^CODEAPI_EXECUTION_MANIFEST_PRIVATE_KEY=//p' "$ENV_FILE" | tail -1)"
if ! printf '%s' "$manifest_key" | base64 -d 2>/dev/null | openssl pkey -inform DER -noout 2>/dev/null; then
    umask 077
    printf '\nCODEAPI_EXECUTION_MANIFEST_PRIVATE_KEY=%s\n' \
        "$(openssl genpkey -algorithm ED25519 -outform DER 2>/dev/null | base64 -w 0)" >> "$ENV_FILE"
fi

private_key_base64="$(sed -n 's/^CODEAPI_JWT_PRIVATE_KEY_BASE64=//p' "$ENV_FILE")"
test -n "$private_key_base64"
cat > "$LIBRECHAT_OVERRIDE" <<EOF
# Generated by bootstrap-code-interpreter.sh; do not edit or commit.
services:
  moqui-librechat:
    environment:
      - LIBRECHAT_CODE_BASEURL=http://moqui-codeapi-api:3112/v1
      - LIBRECHAT_CODE_BASEURL_STATEFUL=http://moqui-codeapi-api:3112/v1
      - CODEAPI_AUTH_PROVIDER=librechat-jwt
      - CODEAPI_JWT_PRIVATE_KEY_BASE64=$private_key_base64
      - CODEAPI_JWT_ALGORITHM=EdDSA
      - CODEAPI_JWT_KID=moqui-codeapi-1
      - CODEAPI_JWT_ISSUER=librechat
      - CODEAPI_JWT_AUDIENCE=codeapi
      - CODEAPI_JWT_TTL_SECONDS=300
      - CODEAPI_JWT_SINGLE_TENANT_ID=moqui
      - CODE_ENVIRONMENT_DECISION_VERSION=1
EOF

echo "Prepared Code Interpreter $REF in $SOURCE_DIR"
echo "Next: ./start-code-interpreter.sh"
